-- 10. TABELA DE CONFIGURAÇÕES GERAIS
CREATE TABLE IF NOT EXISTS public.configuracoes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  meses_retencao_midia int DEFAULT 3,
