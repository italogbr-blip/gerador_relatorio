-- =====================================================================
-- 003_configuracoes_popups.sql
-- Tabela para armazenamento de configurações de rodapé e popups do sistema
-- =====================================================================

CREATE TABLE IF NOT EXISTS public.configuracoes_popups (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mensagem text,
  estilo character varying(50),
  duracao integer DEFAULT 5000,
  frequencia character varying(20) DEFAULT 'uma_vez'
);

-- Ativar RLS
ALTER TABLE public.configuracoes_popups ENABLE ROW LEVEL SECURITY;

-- Política de acesso total
DROP POLICY IF EXISTS "Permitir total configuracoes_popups" ON public.configuracoes_popups;
CREATE POLICY "Permitir total configuracoes_popups" ON public.configuracoes_popups 
  FOR ALL TO public 
  USING (true) 
  WITH CHECK (true);

-- Permissões para as roles pública e autenticada
GRANT ALL ON TABLE public.configuracoes_popups TO anon, authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;
