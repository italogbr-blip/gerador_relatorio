-- Sistema de autorização de cadastro, notificações e auditoria de aprovações/recusas
-- =====================================================================

-- 1. Adiciona a configuração de exigência de aprovação na tabela public.configuracoes
ALTER TABLE public.configuracoes ADD COLUMN IF NOT EXISTS exigir_aprovacao_cadastro boolean DEFAULT false;

-- 2. Adiciona o status de aprovação na tabela public.usuarios
ALTER TABLE public.usuarios ADD COLUMN IF NOT EXISTS status_aprovacao character varying(20) DEFAULT 'aprovado';
ALTER TABLE public.usuarios ADD COLUMN IF NOT EXISTS aprovado_por character varying(100);
ALTER TABLE public.usuarios ADD COLUMN IF NOT EXISTS data_aprovacao timestamp with time zone;

-- Todos os usuários atuais são marcados como aprovados
UPDATE public.usuarios SET status_aprovacao = 'aprovado' WHERE status_aprovacao IS NULL;

-- 3. Tabela de histórico e auditoria de cada liberação ou recusa
CREATE TABLE IF NOT EXISTS public.historico_aprovacoes_usuarios (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id bigint REFERENCES public.usuarios(id) ON DELETE CASCADE,
  username character varying(100),
  nome character varying(255),
  email character varying(255),
  acao character varying(20) NOT NULL, -- 'aprovado' ou 'recusado'
  motivo text,
  executado_por character varying(100) DEFAULT 'Coordenação',
  data_registro timestamp with time zone DEFAULT NOW()
);

ALTER TABLE public.historico_aprovacoes_usuarios ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir total historico_aprovacoes_usuarios" ON public.historico_aprovacoes_usuarios;
CREATE POLICY "Permitir total historico_aprovacoes_usuarios" ON public.historico_aprovacoes_usuarios 
  FOR ALL TO public 
  USING (true) 
  WITH CHECK (true);

GRANT ALL ON TABLE public.historico_aprovacoes_usuarios TO anon, authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;

-- Força recarregar o schema cache do PostgREST
NOTIFY pgrst, 'reload schema';
